#!/usr/bin/env python3
"""Adds recipes to manger/ and rebuilds the recipe list on its home page, manger/index.html.

Every recipe is a self-contained page at manger/<slug>/index.html. Its type (Entrée, Plat or Dessert),
cuisine and sources are written in its <head> as <meta name="recipe:course">, <meta name="recipe:cuisine">
and <meta name="recipe:source"> (several sources are separated by commas). The home page lists the
recipes by type, each tile showing its cuisine's flag; its filters (type, cuisine, source) are generated
from those tags, so a new cuisine or source appears on the home page as soon as one recipe uses it. A cuisine's round flag is
manger/flags/<cuisine>.svg (flags/italienne.svg); the build says when a cuisine has none.

  ./build-recipes.py add <file.html> <type> <cuisine> <source> [source ...]
      Copies the page to manger/<slug>/index.html (the slug comes from its <title>), writes the tags,
      links it to favicon.svg (the tab icon), style.css (the shared look) and recipe.js (back link, print button, tag chips, visit counter) and rebuilds the home page.
      <type> is Entrée, Plat or Dessert.
      e.g. ./build-recipes.py add ~/Downloads/Pad_Thai.html Plat Thaïe Yasmine
           ./build-recipes.py add ~/Downloads/Kibbeh.html Entrée Libanaise Sylvie "Les recettes de Nadia"
      Options: --slug <slug> to choose the address, --force to replace an existing recipe.

  ./build-recipes.py build
      Rebuilds the home page. Run it after editing a recipe's tags or title, or deleting a recipe.
"""
import argparse
import html
import re
import shutil
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent / "manger"
INDEX = ROOT / "index.html"
# The home page has two generated parts: the filters, in its top band, and the list of recipes below.
GENERATED = "(generated by ./build-recipes.py build: edit the recipes, not this)"
BLOCKS = {"filters": ("<!-- filters:start %s -->" % GENERATED, "<!-- filters:end -->"),
          "recipes": ("<!-- recipes:start %s -->" % GENERATED, "<!-- recipes:end -->")}
# The home page's sections, in the order of a meal: (value of recipe:course, section title).
COURSES = [("Entrée", "Entrées"), ("Plat", "Plats"), ("Dessert", "Desserts")]
TAG_LINE = re.compile(r'^\s*<(meta name="recipe:[a-z]+"[^>]*|link rel="(?:stylesheet|icon)" [^>]*href="\.\./(?:style\.css|favicon\.svg)"[^>]*|script src="\.\./recipe\.js"[^>]*></script)>\s*\n', re.M)


def slugify(text):
    text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def title_of(page):
    m = re.search(r"<title>(.*?)</title>", page, re.S | re.I)
    return html.unescape(m.group(1)).strip() if m else None


def tag_values(page, name):
    m = re.search(r'<meta name="recipe:%s" content="([^"]*)"' % name, page)
    return [v.strip() for v in html.unescape(m.group(1)).split(",") if v.strip()] if m else []


def add(args):
    src = Path(args.file).expanduser()
    page = src.read_text(encoding="utf-8")
    title = title_of(page)
    if not title:
        sys.exit(f"{src}: no <title>, which is the recipe's name on the home page")
    if "</head>" not in page:
        sys.exit(f"{src}: no </head>")
    slug = args.slug or slugify(title)
    dest = ROOT / slug / "index.html"
    if dest.exists() and not args.force:
        sys.exit(f"{slug}/ already exists (use --force to replace it, or --slug to pick another address)")

    course = args.course.strip().capitalize()
    if course not in dict(COURSES):
        sys.exit(f"{course}: the type must be one of {', '.join(c for c, _ in COURSES)}")
    sources = [s.strip() for arg in args.sources for s in arg.split(",") if s.strip()]
    tags = (
        f'<meta name="recipe:course" content="{html.escape(course)}">\n'
        f'<meta name="recipe:cuisine" content="{html.escape(args.cuisine.strip())}">\n'
        f'<meta name="recipe:source" content="{html.escape(", ".join(sources))}">\n'
        '<link rel="icon" type="image/svg+xml" href="../favicon.svg">\n'
        '<link rel="stylesheet" href="../style.css">\n'
        '<script src="../recipe.js" defer></script>\n'
    )
    page = TAG_LINE.sub("", page)
    page = page.replace("</head>", tags + "</head>", 1)
    dest.parent.mkdir(exist_ok=True)
    dest.write_text(page, encoding="utf-8")
    print(f"manger/{slug}/  {title}  ({course}; {args.cuisine}; {', '.join(sources)})")
    build()


def build(args=None):
    recipes = []
    for path in sorted(ROOT.glob("*/index.html")):
        page = path.read_text(encoding="utf-8")
        where = path.relative_to(ROOT)
        title, cuisine, sources = title_of(page), tag_values(page, "cuisine"), tag_values(page, "source")
        course = tag_values(page, "course")
        if not title or len(cuisine) != 1 or not sources or len(course) != 1 or course[0] not in dict(COURSES):
            sys.exit(f"{where}: needs a <title>, one recipe:course ({', '.join(c for c, _ in COURSES)}), "
                     "one recipe:cuisine and at least one recipe:source")
        recipes.append({"slug": path.parent.name, "title": title, "course": course[0], "cuisine": cuisine[0],
                        "sources": sources})

    def count(values):
        n = {}
        for v in values:
            n[v] = n.get(v, 0) + 1
        return sorted(n.items(), key=lambda kv: slugify(kv[0]))

    def flag(cuisine, title=""):
        # A cuisine's round flag is manger/flags/<cuisine>.svg (e.g. flags/italienne.svg), if there is one.
        name = f"flags/{slugify(cuisine)}.svg"
        alt = f' alt="{html.escape(title)}" title="{html.escape(title)}"' if title else ' alt=""'
        return f'<img class="flag" src="{name}"{alt} width="18" height="18">' if (ROOT / name).exists() else ""

    def chips(kind, label, values, order=None):
        # on phones, only the Type row shows until "Filtres" is tapped (the others are class "filter more")
        more = "" if kind == "course" else " more"
        out = [f'  <div class="filter{more}" data-kind="{kind}"><span class="label">{label}</span>',
               f'    <a class="chip" href="./" data-kind="{kind}" data-value="">Toutes</a>']
        counted = count(values)
        if order:
            counted = sorted(counted, key=lambda kv: order.index(kv[0]))
        for value, n in counted:
            v = html.escape(value)
            icon = flag(value) if kind == "cuisine" else ""
            shown = html.escape(dict(COURSES)[value]) if kind == "course" else v
            out.append(f'    <a class="chip" href="?{kind}={v}" data-kind="{kind}" data-value="{v}">{icon}{shown} <span class="n">{n}</span></a>')
        out.append("  </div>")
        return out

    e = html.escape
    filters = ['<nav class="filters" aria-label="Filtrer les recettes">']
    filters += chips("course", "Type", [r["course"] for r in recipes], [c for c, _ in COURSES])
    filters += chips("cuisine", "Cuisine", [r["cuisine"] for r in recipes])
    filters += chips("source", "Source", [s for r in recipes for s in r["sources"]])
    filters.append("</nav>")
    lines = []
    for course, heading in COURSES:
        mine = sorted((r for r in recipes if r["course"] == course), key=lambda r: slugify(r["title"]))
        if not mine:
            continue
        n = len(mine)
        lines.append(f'<section data-course="{e(course)}">')
        lines.append(f'  <h2>{e(heading)} <span class="count">{n} recette{"s" if n != 1 else ""}</span></h2>')
        lines.append('  <ul class="recipes">')
        for r in mine:
            tags = " ".join(f'<a class="tag" href="?source={e(s)}">{e(s)}</a>' for s in r["sources"])
            lines.append(f'    <li data-course="{e(course)}" data-cuisine="{e(r["cuisine"])}" data-source="{e("|".join(r["sources"]))}">'
                         f'{flag(r["cuisine"], r["cuisine"])}<a class="name" href="{r["slug"]}/">{e(r["title"])}</a> '
                         f'<span class="tags">{tags}</span></li>')
        lines.append("  </ul>")
        lines.append("</section>")
    index = INDEX.read_text(encoding="utf-8")
    for name, body in (("filters", filters), ("recipes", lines)):
        start, end = BLOCKS[name]
        if start not in index or end not in index:
            sys.exit(f"index.html: the markers {start} and {end} are missing")
        before, rest = index.split(start, 1)
        index = before + "\n".join([start] + body + [end]) + rest.split(end, 1)[1]
    INDEX.write_text(index, encoding="utf-8")
    print(f"manger/index.html: {len(recipes)} recipe{'s' if len(recipes) != 1 else ''}")
    for cuisine, _ in count(r["cuisine"] for r in recipes):
        if not flag(cuisine):
            print(f"  no flag for {cuisine}: add manger/flags/{slugify(cuisine)}.svg (the country's aircraft roundel, 24x24)")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("add", help="add a recipe page")
    p.add_argument("file")
    p.add_argument("course", metavar="type")
    p.add_argument("cuisine")
    p.add_argument("sources", nargs="+", metavar="source")
    p.add_argument("--slug")
    p.add_argument("--force", action="store_true")
    p.set_defaults(run=add)
    sub.add_parser("build", help="rebuild the home page").set_defaults(run=build)
    args = parser.parse_args()
    args.run(args)


if __name__ == "__main__":
    main()
