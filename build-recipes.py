#!/usr/bin/env python3
"""Adds recipes to manger/ and rebuilds the recipe list on its home page, manger/index.html.

Every recipe is a self-contained page at manger/<slug>/index.html. Its cuisine and sources are written in
its <head> as <meta name="recipe:cuisine"> and <meta name="recipe:source"> (several sources are
separated by commas). The home page's list and filters are generated from those tags, so a new
cuisine or source appears on the home page as soon as one recipe uses it.

  ./build-recipes.py add <file.html> <cuisine> <source> [source ...]
      Copies the page to manger/<slug>/index.html (the slug comes from its <title>), writes the tags,
      links it to style.css (the shared look) and recipe.js (back link, print button, tag chips, visit counter) and rebuilds the home page.
      e.g. ./build-recipes.py add ~/Downloads/Pad_Thai.html Thaïe Yasmine
           ./build-recipes.py add ~/Downloads/Kibbeh.html Libanaise Sylvie "Les recettes de Nadia"
      Options: --slug <slug> to choose the address, --force to replace an existing recipe.

  ./build-recipes.py build
      Rebuilds the home page. Run it after editing a recipe's tags or title, or deleting a recipe.
"""
import argparse
import html
import re
import shutil
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent / "manger"
INDEX = ROOT / "index.html"
START = "<!-- recipes:start (generated by ./build-recipes.py build: edit the recipes, not this) -->"
END = "<!-- recipes:end -->"
TAG_LINE = re.compile(r'^\s*<(meta name="recipe:[a-z]+"[^>]*|link rel="stylesheet" href="\.\./style\.css"[^>]*|script src="\.\./recipe\.js"[^>]*></script)>\s*\n', re.M)


def slugify(text):
    text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def title_of(page):
    m = re.search(r"<title>(.*?)</title>", page, re.S | re.I)
    return html.unescape(m.group(1)).strip() if m else None


def tag_values(page, name):
    m = re.search(r'<meta name="recipe:%s" content="([^"]*)"' % name, page)
    return [v.strip() for v in html.unescape(m.group(1)).split(",") if v.strip()] if m else []


def add(args):
    src = Path(args.file).expanduser()
    page = src.read_text(encoding="utf-8")
    title = title_of(page)
    if not title:
        sys.exit(f"{src}: no <title>, which is the recipe's name on the home page")
    if "</head>" not in page:
        sys.exit(f"{src}: no </head>")
    slug = args.slug or slugify(title)
    dest = ROOT / slug / "index.html"
    if dest.exists() and not args.force:
        sys.exit(f"{slug}/ already exists (use --force to replace it, or --slug to pick another address)")

    sources = [s.strip() for arg in args.sources for s in arg.split(",") if s.strip()]
    tags = (
        f'<meta name="recipe:cuisine" content="{html.escape(args.cuisine.strip())}">\n'
        f'<meta name="recipe:source" content="{html.escape(", ".join(sources))}">\n'
        '<link rel="stylesheet" href="../style.css">\n'
        '<script src="../recipe.js" defer></script>\n'
    )
    page = TAG_LINE.sub("", page)
    page = page.replace("</head>", tags + "</head>", 1)
    dest.parent.mkdir(exist_ok=True)
    dest.write_text(page, encoding="utf-8")
    print(f"manger/{slug}/  {title}  ({args.cuisine}; {', '.join(sources)})")
    build()


def build(args=None):
    recipes = []
    for path in sorted(ROOT.glob("*/index.html")):
        page = path.read_text(encoding="utf-8")
        where = path.relative_to(ROOT)
        title, cuisine, sources = title_of(page), tag_values(page, "cuisine"), tag_values(page, "source")
        if not title or len(cuisine) != 1 or not sources:
            sys.exit(f"{where}: needs a <title>, one recipe:cuisine and at least one recipe:source")
        recipes.append({"slug": path.parent.name, "title": title, "cuisine": cuisine[0], "sources": sources})

    def count(values):
        n = {}
        for v in values:
            n[v] = n.get(v, 0) + 1
        return sorted(n.items(), key=lambda kv: slugify(kv[0]))

    def chips(kind, label, values):
        out = [f'  <div class="filter"><span class="label">{label}</span>',
               f'    <a class="chip" href="./" data-kind="{kind}" data-value="">Toutes</a>']
        for value, n in count(values):
            v = html.escape(value)
            out.append(f'    <a class="chip" href="?{kind}={v}" data-kind="{kind}" data-value="{v}">{v} <span class="n">{n}</span></a>')
        out.append("  </div>")
        return out

    e = html.escape
    lines = [START, '<nav class="filters" aria-label="Filtrer les recettes">']
    lines += chips("cuisine", "Cuisine", [r["cuisine"] for r in recipes])
    lines += chips("source", "Source", [s for r in recipes for s in r["sources"]])
    lines.append("</nav>")
    for cuisine, _ in count(r["cuisine"] for r in recipes):
        lines.append(f'<section data-cuisine="{e(cuisine)}">')
        lines.append(f"  <h2>{e(cuisine)}</h2>")
        lines.append('  <ul class="recipes">')
        for r in sorted((r for r in recipes if r["cuisine"] == cuisine), key=lambda r: slugify(r["title"])):
            tags = " ".join(f'<a class="tag" href="?source={e(s)}">{e(s)}</a>' for s in r["sources"])
            lines.append(f'    <li data-cuisine="{e(cuisine)}" data-source="{e("|".join(r["sources"]))}">'
                         f'<a class="name" href="{r["slug"]}/">{e(r["title"])}</a> <span class="tags">{tags}</span></li>')
        lines.append("  </ul>")
        lines.append("</section>")
    lines.append(END)

    index = INDEX.read_text(encoding="utf-8")
    if START not in index or END not in index:
        sys.exit(f"index.html: the markers {START} and {END} are missing")
    before, rest = index.split(START, 1)
    after = rest.split(END, 1)[1]
    INDEX.write_text(before + "\n".join(lines) + after, encoding="utf-8")
    print(f"manger/index.html: {len(recipes)} recipe{'s' if len(recipes) != 1 else ''}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("add", help="add a recipe page")
    p.add_argument("file")
    p.add_argument("cuisine")
    p.add_argument("sources", nargs="+", metavar="source")
    p.add_argument("--slug")
    p.add_argument("--force", action="store_true")
    p.set_defaults(run=add)
    sub.add_parser("build", help="rebuild the home page").set_defaults(run=build)
    args = parser.parse_args()
    args.run(args)


if __name__ == "__main__":
    main()
