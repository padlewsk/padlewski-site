#!/bin/sh
# Gives every page with a language switch one address per language: <page>/fr/, <page>/en/, ...
# Each is a copy of <page>/index.html with <base href="../"> so photos, PDFs and icons still load
# from the page folder; the page's script reads the language from the address.
# Run after editing any <page>/index.html that has a language switch, and commit the copies.
set -e
cd "$(dirname "$0")"

for src in */index.html; do
    page=$(dirname "$src")
    langs=$(grep -o 'data-lang="[a-z]*"' "$src" | sed 's/data-lang="\(.*\)"/\1/')
    [ -n "$langs" ] || continue
    for lang in $langs; do
        mkdir -p "$page/$lang"
        awk '{ print } /^<head>$/ && !done { print "<base href=\"../\">"; print "<!-- generated by build-langs.sh from ../index.html: edit that file, then run the script again -->"; done = 1 }' \
            "$src" > "$page/$lang/index.html"
        grep -q '^<base href="../">$' "$page/$lang/index.html" || { echo "$src: no <head> line" >&2; exit 1; }
        echo "$page/$lang/"
    done
done
